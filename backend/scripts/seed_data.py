def seed_database(db: Session):
    # Ensure default user
    if not db.query(User).filter(User.email == "aryan@aqua-xfoul.com").first():
        admin = User(
            user_uid="usr-aryan",
            name="Aryan Kumar",
            email="aryan@aqua-xfoul.com",
            role="Administrator",
            initials="AK",
        )
        db.add(admin)

    # Cache ship types
    type_cache = {}
    for data in SEED_VESSELS:
        t_name = data["ship_type"]
        if t_name not in type_cache:
            st = db.query(ShipType).filter(ShipType.name.ilike(t_name)).first()
            if not st:
                st = ShipType(name=t_name)
                db.add(st)
                db.flush()
            type_cache[t_name] = st

        # Check existing vessel
        existing = db.query(Vessel).filter(Vessel.imo_number == data["imo_number"]).first()
        if existing:
            continue

        vessel = Vessel(
            imo_number=data["imo_number"],
            name=data["name"],
            yard_number=data.get("yard_number"),
            category=data.get("category"),
            technical_manager=data.get("technical_manager"),
            manager_domicile=data.get("manager_domicile"),
            manager_registration=data.get("manager_registration"),
            ship_type_id=type_cache[t_name].id,
            deadweight=data.get("deadweight"),
            gross_tonnage=data.get("gross_tonnage"),
            teu=data.get("teu"),
            teu_14=data.get("teu_14"),
            flag=data.get("flag"),
            built_year=data.get("built_year"),
            length=data.get("length"),
            breadth=data.get("breadth"),
            draught=data.get("draught"),
            service_speed=data.get("service_speed"),
            speed_knots=data.get("service_speed"),
            fuel_consumption_tons_per_day=data.get("fuel_consumption_tons_per_day"),
            status=data.get("status", "Active"),
            fouling_risk=data.get("fouling_risk", "Low"),
            fouling_rating=data.get("fouling_rating", Decimal("10.0")),
            last_inspection_date=data.get("last_inspection_date"),
            next_cleaning_due_date=data.get("next_cleaning_due_date"),
            current_route=data.get("current_route"),
        )
        db.add(vessel)
        db.flush()

        # Add sample inspection
        insp = InspectionRecord(
            vessel_id=vessel.id,
            date=data.get("last_inspection_date", "2026-08-01"),
            type="Underwater Drone / ROV",
            inspector="Lloyd's Register Biofouling Surveyor",
            location="Jurong Port Anchorage",
            hull_rating=Decimal("4.2"),
            propeller_condition="Clean" if vessel.fouling_risk == "Low" else "Light Slime",
            findings="Microfouling biofilm detected on flat bottom area. Sea chests show early barnacle settlement.",
            status="Completed",
        )
        db.add(insp)

        # Add sample fouling assessment
        foul = FoulingAssessment(
            vessel_id=vessel.id,
            date=data.get("last_inspection_date", "2026-08-01"),
            risk_level=vessel.fouling_risk,
            fouling_coverage_pct=Decimal("14.5") if vessel.fouling_risk == "Low" else Decimal("32.0"),
            roughness_microns=Decimal("185.0"),
            speed_loss_pct=Decimal("0.8") if vessel.fouling_risk == "Low" else Decimal("2.4"),
            excess_fuel_pct=Decimal("2.2") if vessel.fouling_risk == "Low" else Decimal("8.6"),
            estimated_co2_penalty_tons=Decimal("38.4"),
            assessed_by="Aqua-X-Foul BioAI Engine v2.4",
        )
        db.add(foul)

        # Add sample cleaning event
        clean = CleaningEvent(
            vessel_id=vessel.id,
            date="2026-04-12",
            location="Rotterdam Anchorage",
            provider="Subsea Clean Tech BV",
            method="In-Water ROV Hull Cleaning",
            status="Completed",
            before_rating=Decimal("38.5"),
            after_rating=Decimal("4.2"),
            efficiency_gain_pct=Decimal("12.4"),
            cost_usd=Decimal("28500.00"),
            co2_saved_tons_est=Decimal("184.2"),
        )
        db.add(clean)

        # Add sample performance record
        perf = PerformanceRecord(
            vessel_id=vessel.id,
            date="2026-09-20",
            speed_knots=Decimal("18.2"),
            fuel_consumption_tons_per_day=Decimal("46.2"),
            slip_ratio_pct=Decimal("4.8"),
            weather_beaufort=3,
            excess_fuel_penalty_pct=Decimal("1.8"),
        )
        db.add(perf)

    db.commit()
    print("Database seeding completed with fleet dataset!")


if __name__ == "__main__":
    from app.database.session import SessionLocal
