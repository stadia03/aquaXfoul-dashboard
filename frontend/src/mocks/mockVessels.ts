// Helper to generate the full realistic 142-vessel fleet matching statistical distributions
export function generateFullFleet(): Vessel[] {
  const fleet: Vessel[] = [...mockVessels];
  const managers = [
    { name: 'Bernhard Schulte Shipmanagement', domicile: 'Singapore' },
    { name: 'Columbia Shipmanagement', domicile: 'Cyprus' },
    { name: 'Fleet Management Limited', domicile: 'Hong Kong' },
    { name: 'V.Group / V.Ships', domicile: 'United Kingdom' },
    { name: 'Anglo-Eastern Ship Management', domicile: 'Hong Kong' },
    { name: 'Eastern Pacific Shipping', domicile: 'Singapore' },
    { name: 'Wilhelmsen Ship Management', domicile: 'Norway' },
    { name: 'MOL LNG Transport', domicile: 'Japan' },
    { name: 'Euronav Ship Management', domicile: 'Belgium' },
    { name: 'Frontline Management', domicile: 'Bermuda' },
  ];

  const types: { type: Vessel['type']; category: string; count: number }[] = [
    { type: 'Container Ship', category: 'Container Ship', count: 34 },
    { type: 'Bulk Carrier', category: 'Bulk Carrier', count: 28 },
    { type: 'General Cargo', category: 'General Cargo', count: 18 },
    { type: 'LNG Carrier', category: 'LNG – Conventional Gas Carrier', count: 16 },
    { type: 'Cruise', category: 'Cruise', count: 12 },
    { type: 'Other', category: 'Specialized Tanker & Offshore', count: 34 },
  ];

  // We have 12 initial vessels, expand to 142
  let imoSeed = 9811000;
  let idSeed = 13;

  for (const t of types) {
    const existingCount = fleet.filter(v => v.type === t.type).length;
    const needed = t.count - existingCount;

    for (let i = 0; i < needed; i++) {
      imoSeed += 7;
      idSeed++;
      const mgr = managers[i % managers.length];
      
      // Distribute risks: 45 low, 30 mod, 18 high, 8 crit across the remaining
      const rand = (idSeed * 17) % 100;
      let risk: Vessel['foulingRisk'] = 'Low';
      let rating = 15;
      let status: Vessel['status'] = 'Active';

      if (rand < 50) {
        risk = 'Low';
        rating = 10 + (rand % 15);
      } else if (rand < 80) {
        risk = 'Moderate';
        rating = 35 + (rand % 20);
      } else if (rand < 93) {
        risk = 'High';
        rating = 60 + (rand % 15);
      } else {
        risk = 'Critical';
        rating = 80 + (rand % 18);
        status = idSeed % 2 === 0 ? 'In Maintenance' : 'Active';
      }

      fleet.push({
        id: `v-${imoSeed}`,
        imo: imoSeed.toString(),
        name: `${t.type.split(' ')[0]} ${['Valor', 'Vanguard', 'Horizon', 'Sentinel', 'Crest', 'Voyager', 'Aurora', 'Titan', 'Endeavour', 'Legacy'][i % 10]} ${idSeed}`,
        yardNumber: `YD-20${15 + (i % 9)}-${100 + i}`,
        type: t.type,
        category: t.category,
        technicalManager: mgr.name,
        managerDomicile: mgr.domicile,
        managerRegistration: `${mgr.domicile.substring(0, 2).toUpperCase()}-REG-${30000 + i * 142}`,
        dwt: 45000 + (i * 3100) % 95000,
        gt: 28000 + (i * 2400) % 75000,
        teu: t.type === 'Container Ship' ? 6000 + (i * 800) % 12000 : undefined,
        teu14: t.type === 'Container Ship' ? 4500 + (i * 600) % 9000 : undefined,
        builtYear: 2014 + (i % 11),
        flag: ['Singapore (SGP)', 'Liberia (LBR)', 'Panama (PAN)', 'Marshall Islands (MHL)', 'Hong Kong (HKG)', 'Bahamas (BHS)'][i % 6],
        lengthMeters: 180 + (i * 4) % 180,
        beamMeters: 28 + (i % 24),
        draftMeters: 9.5 + (i % 7) * 0.8,
        status,
        foulingRisk: risk,
        foulingRating: rating,
        lastInspectionDate: `${1 + (i % 28)} Aug 2026`,
        nextCleaningDueDate: `${5 + (i % 25)} ${['Oct 2026', 'Nov 2026', 'Dec 2026', 'Jan 2027', 'Feb 2027'][i % 5]}`,
        currentRoute: 'Global Commercial Route',
        speedKnots: 13.5 + (i % 7),
        fuelConsumptionTonsPerDay: 28.0 + (i % 45),
      });
    }
  }

  return fleet.slice(0, 142);
}
